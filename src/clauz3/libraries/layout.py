"""Where a project's trusted layers live on disk.

Installed libraries go under ``<project>/.clauz3/tools/<domain>/trusted/``, out
of the way of the project's own files. Layers a project authors itself (and
library sources, examples and the bundled stdlib) keep the plain
``<project>/tools/<domain>/trusted/`` layout.

Both directories hold the same ``tools`` namespace package, so agent programs
import ``tools.<domain>.trusted`` whichever one provides the domain. A project
with installed libraries therefore has two import roots, ``<project>/.clauz3``
and ``<project>``; :func:`expand_import_roots` derives them from the project
directory so every caller selects the same, ordered layer.
"""

import keyword
import warnings
from collections.abc import Iterable, Sequence
from pathlib import Path

#: Per-project directory owned by clauz3.
PROJECT_DIR = ".clauz3"

#: The import package that holds trusted layers, in either location.
TOOLS_PACKAGE = "tools"

#: The package name that marks a domain's trusted layer.
TRUSTED_PACKAGE = "trusted"

#: How many directories a domain may span under ``tools/``: a flat
#: ``tools/<domain>/trusted`` or an org-namespaced
#: ``tools/<org>/<domain>/trusted``. Deeper candidates are skipped with a
#: warning so the trusted boundary stays auditable from two globs.
MAX_DOMAIN_DEPTH = 2

_GITIGNORE = "# Generated by clauz3. Commit installed libraries; ignore caches.\n"
_IGNORED = (
    "__pycache__/",
    "*.pyc",
    "install-*/",
    "library-backups/",
    "approval-service.json",
)


class LayoutError(ValueError):
    """The project's installed and authored layers cannot be combined."""


class SkippedLayerWarning(UserWarning):
    """A ``trusted`` directory was found but cannot be used as a trusted layer."""


def domain_problem(parts: Sequence[str]) -> str | None:
    """Why a domain path under ``tools/`` cannot be a trusted layer, or None.

    A domain is imported as ``tools.<part>...trusted``, so every part must be a
    Python identifier and not a keyword, and it may nest at most
    :data:`MAX_DOMAIN_DEPTH` levels.

    >>> domain_problem(["lims"]) is None
    True
    >>> domain_problem(["acme", "lims"]) is None
    True
    >>> domain_problem(["acme-labs", "lims"])
    "'acme-labs' is not a Python identifier, so it cannot be imported"
    >>> domain_problem(["class"])
    "'class' is a Python keyword, so it cannot be imported"
    >>> domain_problem(["a", "b", "c"])
    'domains nest at most 2 levels under tools/ (tools/<org>/<domain>/trusted)'
    >>> domain_problem([])
    'a trusted layer needs a domain directory (tools/<domain>/trusted)'
    """
    if not parts:
        return "a trusted layer needs a domain directory (tools/<domain>/trusted)"
    if len(parts) > MAX_DOMAIN_DEPTH:
        return (
            f"domains nest at most {MAX_DOMAIN_DEPTH} levels under tools/ "
            "(tools/<org>/<domain>/trusted)"
        )
    for part in parts:
        if not part.isidentifier():
            return f"{part!r} is not a Python identifier, so it cannot be imported"
        if keyword.iskeyword(part):
            return f"{part!r} is a Python keyword, so it cannot be imported"
    return None


def trusted_dirs(tools: Path) -> list[Path]:
    """Every usable ``<domain>/trusted`` directory below ``tools``, sorted.

    This is the one discovery rule shared by ``clauz3 install`` (which domains
    a source provides), the runtime (which roots ``run``, ``tools``,
    ``policy-check`` and session launch trust by default). The workspace
    library listing deliberately does not use it: it shows an unimportable
    domain as unmanageable rather than hiding it. A candidate is skipped when:

    - it is a symlink or reached through one below ``tools`` (silently; the
      installer's ``_reject_symlinks`` is the load-bearing check),
    - it lies inside an already accepted trusted directory (silently; it is
      already part of that layer), or
    - its domain cannot be imported (see :func:`domain_problem`), with a
      :class:`SkippedLayerWarning`, so one badly named directory does not
      abort every command that discovers roots.
    """
    accepted: list[Path] = []
    if not tools.is_dir():
        return accepted
    for candidate in sorted(tools.rglob(TRUSTED_PACKAGE)):
        if not candidate.is_dir() or has_symlink_component(candidate, tools):
            continue
        if any(candidate.is_relative_to(root) for root in accepted):
            continue
        problem = domain_problem(candidate.parent.relative_to(tools).parts)
        if problem is not None:
            warnings.warn(
                f"skipping trusted layer {candidate}: {problem}",
                SkippedLayerWarning,
                stacklevel=2,
            )
            continue
        accepted.append(candidate)
    return accepted


def has_symlink_component(path: Path, base: Path) -> bool:
    """True if ``path`` is, or is reached through, a symlink below ``base``.

    Prevents a symlinked ``trusted`` directory (or a symlinked parent) from
    being discovered as a domain. For installs this is belt-and-suspenders,
    not the load-bearing check: any domain it filters out is one the installer's
    per-domain ``_reject_symlinks`` would later reject anyway (fail-closed
    either way).
    """
    current = path
    while current != base and base in current.parents:
        if current.is_symlink():
            return True
        current = current.parent
    return False


def project_dir(project: Path) -> Path:
    """``<project>/.clauz3``: the import root for installed libraries."""
    return project / PROJECT_DIR


def installed_tools(project: Path) -> Path:
    """``<project>/.clauz3/tools``: where ``clauz3 install`` copies layers."""
    return project_dir(project) / TOOLS_PACKAGE


def authored_tools(project: Path) -> Path:
    """``<project>/tools``: trusted layers the project authors itself."""
    return project / TOOLS_PACKAGE


def tools_dirs(project: Path) -> list[Path]:
    """Every existing ``tools/`` directory of ``project``, installed first."""
    return [
        path
        for path in (installed_tools(project), authored_tools(project))
        if path.is_dir()
    ]


def domain_path(project: Path, domain: str) -> Path:
    """The directory providing ``domain``, preferring an existing one.

    A domain that is not present yet resolves to its installed location.
    """
    for tools in tools_dirs(project):
        if (tools / domain).exists():
            return tools / domain
    return installed_tools(project) / domain


def domain_name(project: Path, trusted_root: Path) -> str:
    """The domain (``a/b``) of ``trusted_root`` under either tools directory."""
    domain = trusted_root.parent
    for tools in (installed_tools(project), authored_tools(project)):
        if domain.is_relative_to(tools):
            return domain.relative_to(tools).as_posix()
    raise ValueError(f"{trusted_root} is not a layer of {project}")


def check_project(project: Path) -> None:
    """Refuse layouts where installed and authored layers would shadow each other.

    ``tools`` is a namespace package split across both directories. A regular
    ``tools/__init__.py`` would hide every installed library, and the same
    top-level package in both directories would merge two unrelated trees.
    """
    installed = installed_tools(project)
    authored = authored_tools(project)
    if not installed.is_dir() or not authored.is_dir():
        return
    for tools in (installed, authored):
        if (tools / "__init__.py").exists():
            raise LayoutError(
                f"{tools / '__init__.py'} makes `tools` a regular package, which "
                "hides the other tools directory; remove it"
            )
    clashes = sorted(_packages(installed) & _packages(authored))
    if clashes:
        listed = ", ".join(clashes)
        raise LayoutError(
            f"{listed} provided by both {installed} and {authored}; keep one copy"
        )


def expand_import_roots(roots: Iterable[Path]) -> list[Path]:
    """Put each root's ``.clauz3`` directory ahead of it.

    The ``.clauz3`` root is included whether or not it exists yet, so a
    selection's identity does not change when the first library is installed
    (an approval service authorizes the exact ordered roots). Idempotent:
    expanding an already expanded selection returns it unchanged, so a root
    list can cross process boundaries and be expanded again.
    """
    result: list[Path] = []
    seen: set[Path] = set()
    for root in roots:
        root = Path(root)
        candidates = [root]
        if root.name != PROJECT_DIR:
            check_project(root)
            candidates.insert(0, project_dir(root))
        for candidate in candidates:
            key = candidate.resolve()
            if key not in seen:
                seen.add(key)
                result.append(candidate)
    return result


def ensure_project_dir(project: Path) -> Path:
    """Create ``.clauz3/`` with a ``.gitignore`` for caches and scratch space."""
    directory = project_dir(project)
    directory.mkdir(parents=True, exist_ok=True)
    gitignore = directory / ".gitignore"
    if not gitignore.exists():
        gitignore.write_text(_GITIGNORE + "".join(f"{p}\n" for p in _IGNORED))
    return directory


def _packages(tools: Path) -> set[str]:
    return {
        entry.name.removesuffix(".py")
        for entry in tools.iterdir()
        if entry.name != "__pycache__"
        and (entry.is_dir() or entry.suffix == ".py")
        and entry.name != "__init__.py"
    }
